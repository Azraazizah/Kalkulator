    private void btnhasilActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnhasilActionPerformed
    switch(pilih) {
        case 1:
            bil2 = Double.parseDouble(bil);
            jumlah = bil1+bil2;
            bil = Double.toString(jumlah);
            tampilTeks.setText(bil);
            break;
        case 2:
            bil2 = Double.parseDouble(bil);
            jumlah = bil1-bil2;
            bil = Double.toString(jumlah);
            tampilTeks.setText(bil);
            break;
        case 3:
            bil2 = Double.parseDouble(bil);
            jumlah = bil1*bil2;
            bil = Double.toString(jumlah);
            tampilTeks.setText(bil);
            break;
        case 4:
            bil2 = Double.parseDouble(bil);
            jumlah = bil1/bil2;
            bil = Double.toString(jumlah);
            tampilTeks.setText(bil);
            break;
        default:
            break;       
    }
    if(jumlah % 1 == 0) {
        tampilTeks.setText (String.valueOf((int) jumlah));
    } else {
        tampilTeks.setText (String.valueOf(jumlah));
        
    }    
            
    }//GEN-LAST:event_btnhasilActionPerformed

